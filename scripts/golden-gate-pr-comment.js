'use strict';

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { buildPatchPreview } = require('../src/core/patch-preview');

function readGatePayload(gatePath) {
  const p = gatePath || path.join(__dirname, '../artifacts/golden-gate/golden-gate.latest.json');
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function loadSource(root, relFile) {
  const full = path.join(root, relFile);
  if (!fs.existsSync(full)) return null;
  return fs.readFileSync(full, 'utf8');
}

function enrichProgramsWithPreviews(payload, root) {
  const enriched = [];
  for (const prog of payload.programs || []) {
    const entry = { ...prog };
    if (prog.brief || prog.selfImprovePayload) {
      entry.brief = prog.brief || prog.selfImprovePayload?.brief;
    }
    if (prog.patchPreview) {
      enriched.push(entry);
      continue;
    }
    const source = loadSource(root, prog.file);
    const improve = prog.selfImprovePayload || null;
    if (source && improve) {
      entry.patchPreview = buildPatchPreview(source, improve, { filename: prog.file });
      entry.brief = improve.brief;
    }
    enriched.push(entry);
  }
  return enriched;
}

function buildPrCommentMarkdown(payload, options = {}) {
  const lines = [
    '## Noeon Golden Gate — AI Path Feedback',
    '',
    `**Status:** ${payload.ok ? 'PASS' : 'FAIL'} | **Programs:** ${payload.summary?.passed}/${payload.summary?.total} | **Conform:** ${payload.conform?.allValid === false ? 'FAIL' : payload.conform?.allValid ? 'PASS' : '—'}`,
    ''
  ];

  if (payload.ok) {
    lines.push('All AI-native proof programs passed Golden Path validation.');
    lines.push('');
    lines.push('> Ready to merge from an AI-native perspective.');
    return lines.join('\n');
  }

  lines.push('Golden Path gate failed. Below are **SELF-Improve** briefs and **patch previews** for AI/human authors.');
  lines.push('');
  lines.push('**Auto-fix:** run `noeon ai remediate <file> --verify` locally, or `npm run gate:golden:remediate -- --force-hello` in CI.');
  lines.push('');
  lines.push('**CI artifacts:** `artifacts/golden-gate/remediated/` and `remediate.manifest.json` when the remediate job runs.');
  lines.push('');

  for (const prog of payload.programs || []) {
    const mark = prog.ok ? 'PASS' : 'FAIL';
    lines.push(`### ${mark} \`${prog.file}\``);
    if (prog.grade) lines.push(`- Grade: **${prog.grade}** (min: ${prog.minGrade || '—'})`);
    if (prog.verdict) lines.push(`- Verdict: \`${prog.verdict}\``);
    for (const err of prog.errors || []) lines.push(`- Error: ${err}`);

    if (prog.brief) {
      lines.push('');
      lines.push('<details>');
      lines.push('<summary>SELF-Improve brief</summary>');
      lines.push('');
      lines.push('```markdown');
      lines.push(prog.brief);
      lines.push('```');
      lines.push('</details>');
    }

    if (prog.patchPreview?.diff) {
      lines.push('');
      lines.push('<details>');
      lines.push('<summary>Suggested patch diff</summary>');
      lines.push('');
      lines.push('```diff');
      lines.push(prog.patchPreview.diff);
      lines.push('```');
      lines.push('</details>');
    }
    lines.push('');
  }

  if (payload.conform && !payload.conform.allValid) {
    lines.push('### Conform parity failed');
    lines.push('Run `noeon conform parity --json` locally for surface parity details.');
    lines.push('');
  }

  lines.push('---');
  lines.push('*Generated by `scripts/golden-gate-pr-comment.js` — Epoch 3 AI feedback loop*');

  return lines.join('\n');
}

function postPrComment(body, options = {}) {
  const token = options.token || process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
  const repo = options.repo || process.env.GITHUB_REPOSITORY;
  const pr = options.pr || resolvePrNumberFromEvent() || process.env.GITHUB_EVENT_PULL_REQUEST_NUMBER;

  if (!token || !repo || !pr) {
    return { posted: false, reason: 'missing token, repo, or PR number' };
  }

  const marker = '<!-- noeon-golden-gate -->';
  const fullBody = `${marker}\n${body}`;
  const tmpPath = path.join(__dirname, '../artifacts/golden-gate/.pr-comment-body.txt');
  fs.mkdirSync(path.dirname(tmpPath), { recursive: true });
  fs.writeFileSync(tmpPath, fullBody, 'utf8');

  const env = { ...process.env, GH_TOKEN: token, GITHUB_TOKEN: token };
  const endpoint = `repos/${repo}/issues/${pr}/comments`;

  const list = spawnSync('gh', ['api', endpoint, '--jq', '.[].id'], { encoding: 'utf8', env });
  if (list.status === 0 && list.stdout) {
    const ids = list.stdout.trim().split('\n').filter(Boolean);
    for (const id of ids.slice(-30)) {
      const detail = spawnSync('gh', ['api', `repos/${repo}/issues/comments/${id}`, '--jq', '.body'], { encoding: 'utf8', env });
      if (detail.stdout?.includes(marker)) {
        const upd = spawnSync('gh', ['api', '-X', 'PATCH', `repos/${repo}/issues/comments/${id}`, '-F', `body@${tmpPath}`], { env });
        return { posted: upd.status === 0, updated: true, commentId: id };
      }
    }
  }

  const create = spawnSync('gh', ['api', endpoint, '-F', `body@${tmpPath}`], { env });
  return {
    posted: create.status === 0,
    updated: false,
    reason: create.status !== 0 ? (create.stderr?.toString() || 'gh failed') : null
  };
}

function resolvePrNumberFromEvent() {
  const eventPath = process.env.GITHUB_EVENT_PATH;
  if (!eventPath || !fs.existsSync(eventPath)) return null;
  try {
    const event = JSON.parse(fs.readFileSync(eventPath, 'utf8'));
    return event.pull_request?.number || event.issue?.number || null;
  } catch {
    return null;
  }
}

function main() {
  const args = process.argv.slice(2);
  const shouldPost = args.includes('--post');
  const root = path.join(__dirname, '..');
  const payload = readGatePayload();

  if (!payload) {
    console.error('No golden-gate.latest.json found — run npm run gate:golden first');
    process.exit(1);
  }

  payload.programs = enrichProgramsWithPreviews(payload, root);
  const markdown = buildPrCommentMarkdown(payload);
  const outDir = path.join(root, 'artifacts/golden-gate');
  fs.mkdirSync(outDir, { recursive: true });
  const mdPath = path.join(outDir, 'golden-gate.pr-comment.md');
  fs.writeFileSync(mdPath, markdown, 'utf8');
  console.log(`PR comment written: ${mdPath}`);

  if (shouldPost) {
    const pr = resolvePrNumberFromEvent() || process.env.GITHUB_REF?.match(/(\d+)$/)?.[1];
    const result = postPrComment(markdown, { pr });
    console.log('Post result:', JSON.stringify(result));
    if (!result.posted && process.env.CI) {
      console.warn('Could not post PR comment:', result.reason);
    }
  }

  if (!payload.ok) {
    console.log('\n--- PR Comment Preview ---\n');
    console.log(markdown);
  }

  process.exit(0);
}

if (require.main === module) {
  main();
}

module.exports = {
  buildPrCommentMarkdown,
  enrichProgramsWithPreviews,
  postPrComment,
  readGatePayload
};
