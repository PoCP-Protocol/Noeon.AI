'use strict';

const { buildNextPhaseResult } = require('../src/vm/result-assembly-kernel');

let passed = 0;
let failed = 0;

function assert(cond, msg) {
  if (cond) {
    passed += 1;
    console.log(`  \x1b[32mPASS\x1b[0m ${msg}`);
  } else {
    failed += 1;
    console.log(`  \x1b[31mFAIL\x1b[0m ${msg}`);
  }
}

console.log('\n\x1b[36m═══ Result Assembly Kernel v1 Tests ═══\x1b[0m\n');

(() => {
  const result = buildNextPhaseResult({
    next: {
      goal: { text: 'ship safely' },
      models: [{ name: 'm1' }],
      acts: [{ action: 'ship' }],
      reflects: [{ method: 'causal' }],
      evolves: [{ mutation: 'x' }],
      selfModels: [{ identity: 'ops' }],
      myths: [{ text: 'protect value' }]
    },
    blocked: false,
    blockReason: null,
    selectedStrategy: { name: 'beta' },
    guarantees: [{ name: 'g1' }],
    vows: [{ name: 'v1' }],
    constitutions: [{ name: 'c1' }],
    rituals: [{ name: 'r1' }],
    ritualConflicts: [{ type: 'override' }],
    actsPlanned: [{ action: 'ship', ritualBoost: 0.2 }],
    reflection: { verdict: 'stable' },
    evolution: { mode: 'proposed' },
    nextMemory: { runCount: 1 },
    runtimeNext: { strategies: [] },
    field: {
      dominant: { name: 'alpha', energy: 0.91 },
      emissions: [{ kind: 'e1' }],
      woven: [{ step: 1 }],
      dreams: [{ id: 'd1' }],
      hybridDreams: [{ id: 'hd1' }],
      dreamFeedback: { applied: [] },
      memory: { restored: ['k1'] },
      recall: { hit: true },
      declaredSpawns: [{ name: 's1' }],
      narrative: ['n1'],
      flux: [{ crystal: 'f1' }],
      bonds: { autoGenerated: [] },
      spawns: { autoGenerated: [] }
    },
    fieldMemory: { path: 'mem.json', runs: 2, semantic: { edges: [] }, lineage: [{ x: 1 }, { x: 2 }] },
    echoResult: { written: [{ into: 'chan1' }] },
    fluxCrystals: [{ id: 'fc1' }],
    myceliumRuntime: { published: true },
    hotReload: { applied: true },
    strict: true,
    governanceDecision: { winner: 'ritual' },
    hasLivingField: true
  });

  assert(result.profile === 'next', 'buildNextPhaseResult sets next profile');
  assert(result.goal && result.goal.text === 'ship safely', 'buildNextPhaseResult preserves goal payload');
  assert(result.fieldMemory && result.fieldMemory.path === 'mem.json', 'buildNextPhaseResult maps field memory summary when field exists');
  assert(result.fieldMemory && result.fieldMemory.lineage_size === 2, 'buildNextPhaseResult computes lineage size from field memory');
  assert(result.recommendation === 'emit:alpha', 'buildNextPhaseResult computes recommendation from dominant field');
  assert(result.strictMode === true && result.autonomous === true, 'buildNextPhaseResult preserves strict and autonomous flags');

  const blockedResult = buildNextPhaseResult({
    next: {},
    blocked: true,
    blockReason: 'guarantee-failed',
    selectedStrategy: null,
    guarantees: [],
    vows: [],
    constitutions: [],
    rituals: [],
    ritualConflicts: [],
    actsPlanned: [],
    reflection: {},
    evolution: {},
    nextMemory: {},
    runtimeNext: {},
    field: null,
    fieldMemory: null,
    echoResult: { written: [] },
    fluxCrystals: [],
    myceliumRuntime: null,
    hotReload: { applied: false },
    strict: false,
    governanceDecision: {},
    hasLivingField: false
  });

  assert(blockedResult.recommendation === 'halt', 'buildNextPhaseResult prioritizes halt recommendation when blocked');
  assert(blockedResult.fieldMemory === null, 'buildNextPhaseResult omits field memory summary when field is absent');

  console.log(`\n${failed === 0 ? '\x1b[32m' : '\x1b[31m'}${passed} passed, ${failed} failed\x1b[0m\n`);
  process.exit(failed > 0 ? 1 : 0);
})();
